"""Build site/data/picks.json (our opinion picks) from data-src/picks_sf.csv.

    py tools/import_picks.py

The CSV is the editable source, one row per ballot line:
    id, contest, choice, rating, position, source
  rating   "Golden Goose Egg" | "Certified HONK" | blank (an unrated "Goosebase take")
  position our reasoning, already proofread and fact-checked
  source   optional URL backing a factual claim in the position

Rules:
  - Measures (blank choice): one pick. Egg = YES, HONK = NO. An unrated take
    gets `lean` ("yes"/"no") read from its wording ("Vote yes", "Tentative no",
    "Sure.").
  - Offices: rated rows become targeted picks. Unrated text repeated on three or
    more rows of a contest (a slate summary) becomes one contest-wide take with no
    target. Unrated text identical to a rated row's text in the same contest is
    dropped (it's that pick's reasoning, repeated). Anything else is a targeted
    take on that candidate.
"""
import csv
import json
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data-src" / "picks_sf.csv"
OUT = ROOT / "site" / "data" / "picks.json"
VERDICT = {"Golden Goose Egg": "egg", "Certified HONK": "honk", "": "note"}
SLATE_PREFIX = re.compile(r"^(Progressive|Moderate)\.\s+")


def lean(text: str) -> str | None:
    t = text.lower()
    yes = re.search(r"\b(vote|tentative|lean)\s+yes\b|^sure\b", t)
    no = re.search(r"\b(vote|tentative|lean)\s+no\b", t)
    if yes and not no:
        return "yes"
    if no and not yes:
        return "no"
    return None


def main() -> None:
    rows = [r for r in csv.DictReader(SRC.open(encoding="utf-8")) if r["position"].strip()]
    by_contest = defaultdict(list)
    for r in rows:
        by_contest[r["id"]].append(r)
    picks = {}
    for cid, rs in by_contest.items():
        out = []
        if not rs[0]["choice"]:                      # measure
            r = rs[0]
            p = {"verdict": VERDICT[r["rating"].strip()], "reasoning": r["position"].strip()}
            if p["verdict"] == "note" and lean(p["reasoning"]):
                p["lean"] = lean(p["reasoning"])
            if r["source"]:
                p["source"] = r["source"]
            out.append(p)
        else:
            rated_text = {r["position"].strip() for r in rs if r["rating"].strip()}
            counts = defaultdict(int)
            for r in rs:
                if not r["rating"].strip():
                    counts[SLATE_PREFIX.sub("", r["position"].strip())] += 1
            slate_done = set()
            for r in rs:
                text, rating = r["position"].strip(), r["rating"].strip()
                base = SLATE_PREFIX.sub("", text)
                if rating:
                    p = {"verdict": VERDICT[rating], "target": r["choice"], "reasoning": text}
                elif text in rated_text:
                    continue
                elif counts[base] >= 3:
                    if base in slate_done:
                        continue
                    slate_done.add(base)
                    p = {"verdict": "note", "reasoning": base}
                else:
                    p = {"verdict": "note", "target": r["choice"], "reasoning": text}
                if r["source"]:
                    p["source"] = r["source"]
                out.append(p)
        picks[cid] = out
    data = json.loads(OUT.read_text(encoding="utf-8")) if OUT.exists() else {}
    data["picks"] = picks
    data["_about"] = ("OUR recommendations, which are opinion and shown only when the reader turns on picks. "
                      "Generated by tools/import_picks.py from data-src/picks_sf.csv; edit the CSV, not this file. "
                      "verdict: \"egg\" (Golden Goose Egg, positive), \"honk\" (Certified HONK, negative) or \"note\" "
                      "(an unrated Goosebase take; on a measure, `lean` gives the direction). For a measure, egg = YES "
                      "and honk = NO. For offices, `target` names the candidate; a note without a target is a "
                      "contest-wide take. Schema: docs/data-model.md.")
    OUT.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    n = sum(len(v) for v in picks.values())
    kinds = defaultdict(int)
    for v in picks.values():
        for p in v:
            kinds[p["verdict"]] += 1
    print(f"wrote {OUT.relative_to(ROOT)}: {n} picks in {len(picks)} contests {dict(kinds)}")
    for cid, v in picks.items():
        print(f"  {cid:22} " + "; ".join(f"{p['verdict']}{'/' + p['lean'] if p.get('lean') else ''}"
                                         f"{':' + p['target'] if p.get('target') else ''}" for p in v))


if __name__ == "__main__":
    main()
